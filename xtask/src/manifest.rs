//! The vendoring manifest (`stubs/MANIFEST.toml`): which upstream release each vendored tree
//! came from and the SHA-256 of every file in it, plus the check that the tree still matches.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use sha2::{Digest, Sha256};

pub const MANIFEST_PATH: &str = "stubs/MANIFEST.toml";
pub const VENDOR_DIR: &str = "third_party/php-src";
pub const SOURCE: &str = "https://github.com/php/php-src";

const HEADER: &str = "# Generated by `cargo xtask vendor-php-src`; verified by `cargo xtask check-builtins`.\n# Each release lists the SHA-256 of every vendored file under third_party/php-src/<tag>/.\n# Do not edit by hand.\n";

/// One vendored upstream release.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Release {
    /// PHP version, such as `8.5`.
    pub php: String,
    /// Upstream tag, such as `php-8.5.11`.
    pub tag: String,
    /// Full commit SHA the tag points at.
    pub commit: String,
    /// Path (relative to the tree) to SHA-256 of the file contents.
    pub files: BTreeMap<String, String>,
}

/// The SHA-256 of `bytes` as lower-case hex.
pub fn sha256_hex(bytes: &[u8]) -> String {
    let digest = Sha256::digest(bytes);
    digest.iter().fold(String::new(), |mut out, byte| {
        let _ = write!(out, "{byte:02x}");
        out
    })
}

fn quoted(text: &str) -> String {
    format!("{:?}", text)
}

/// The manifest text for `releases`, sorted by PHP version, deterministic.
pub fn render(releases: &[Release]) -> String {
    let mut sorted: Vec<&Release> = releases.iter().collect();
    sorted.sort_by_key(|r| version_key(&r.php));
    let mut out = String::from(HEADER);
    for release in sorted {
        let _ = write!(
            out,
            "\n[[release]]\nphp = {}\ntag = {}\ncommit = {}\nsource = {}\n\n[release.files]\n",
            quoted(&release.php),
            quoted(&release.tag),
            quoted(&release.commit),
            quoted(SOURCE),
        );
        for (path, hash) in &release.files {
            let _ = writeln!(out, "{} = {}", quoted(path), quoted(hash));
        }
    }
    out
}

fn version_key(php: &str) -> Vec<u32> {
    php.split('.').filter_map(|p| p.parse().ok()).collect()
}

/// Reads a manifest; an empty text is an empty manifest.
pub fn parse(text: &str) -> Result<Vec<Release>, String> {
    let table: toml::Table = text.parse().map_err(|e| format!("{MANIFEST_PATH}: {e}"))?;
    let Some(list) = table.get("release") else {
        return Ok(Vec::new());
    };
    let list = list
        .as_array()
        .ok_or("`release` must be an array of tables")?;
    list.iter().map(parse_release).collect()
}

fn parse_release(value: &toml::Value) -> Result<Release, String> {
    let field = |name: &str| {
        value
            .get(name)
            .and_then(|v| v.as_str())
            .map(str::to_string)
            .ok_or_else(|| format!("{MANIFEST_PATH}: a release lacks `{name}`"))
    };
    let files = value
        .get("files")
        .and_then(|f| f.as_table())
        .ok_or_else(|| format!("{MANIFEST_PATH}: a release lacks `files`"))?;
    let mut map = BTreeMap::new();
    for (path, hash) in files {
        let hash = hash
            .as_str()
            .ok_or_else(|| format!("{path}: hash must be a string"))?;
        map.insert(path.clone(), hash.to_string());
    }
    Ok(Release {
        php: field("php")?,
        tag: field("tag")?,
        commit: field("commit")?,
        files: map,
    })
}

/// Reads the manifest under `root`, or an empty one when the file does not exist.
pub fn load(root: &Path) -> Result<Vec<Release>, String> {
    match fs::read_to_string(root.join(MANIFEST_PATH)) {
        Ok(text) => parse(&text),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Vec::new()),
        Err(e) => Err(format!("{MANIFEST_PATH}: {e}")),
    }
}

fn walk(dir: &Path, base: &Path, out: &mut Vec<String>) -> Result<(), String> {
    let entries = fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for entry in entries {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.is_dir() {
            walk(&path, base, out)?;
        } else if let Ok(relative) = path.strip_prefix(base) {
            out.push(relative.to_string_lossy().replace('\\', "/"));
        }
    }
    Ok(())
}

/// Checks the vendored trees under `root` against the manifest: every listed file present and
/// unchanged, no file present that the manifest does not list, no unlisted release directory.
pub fn verify(root: &Path, releases: &[Release]) -> Result<Vec<String>, String> {
    let mut errors = Vec::new();
    let vendor = root.join(VENDOR_DIR);
    for release in releases {
        let base = vendor.join(&release.tag);
        let mut present = Vec::new();
        if base.is_dir() {
            walk(&base, &base, &mut present)?;
        }
        for (path, expected) in &release.files {
            match fs::read(base.join(path)) {
                Ok(bytes) if sha256_hex(&bytes) == *expected => {}
                Ok(_) => errors.push(format!(
                    "{VENDOR_DIR}/{}/{path}: content differs from {MANIFEST_PATH}",
                    release.tag
                )),
                Err(_) => errors.push(format!(
                    "{VENDOR_DIR}/{}/{path}: listed in {MANIFEST_PATH} but missing",
                    release.tag
                )),
            }
        }
        for path in present.iter().filter(|p| !release.files.contains_key(*p)) {
            errors.push(format!(
                "{VENDOR_DIR}/{}/{path}: present but not listed in {MANIFEST_PATH}",
                release.tag
            ));
        }
    }
    if let Ok(entries) = fs::read_dir(&vendor) {
        for entry in entries.flatten() {
            let name = entry.file_name().to_string_lossy().to_string();
            if !releases.iter().any(|r| r.tag == name) {
                errors.push(format!(
                    "{VENDOR_DIR}/{name}: not a release in {MANIFEST_PATH}"
                ));
            }
        }
    }
    errors.sort();
    Ok(errors)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn release() -> Release {
        Release {
            php: "8.5".into(),
            tag: "php-8.5.11".into(),
            commit: "a".repeat(40),
            files: BTreeMap::from([
                ("LICENSE".to_string(), sha256_hex(b"licence")),
                ("ext/x/x.stub.php".to_string(), sha256_hex(b"<?php")),
            ]),
        }
    }

    #[test]
    fn hashes_are_sha256() {
        assert_eq!(
            sha256_hex(b""),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
    }

    #[test]
    fn render_and_parse_round_trip_and_sort_by_version() {
        let mut older = release();
        older.php = "8.0".into();
        older.tag = "php-8.0.30".into();
        let text = render(&[release(), older.clone()]);
        let parsed = parse(&text).unwrap();
        assert_eq!(parsed, vec![older, release()]);
        assert_eq!(render(&parsed), text);
    }

    fn tree(root: &Path) {
        let base = root.join(VENDOR_DIR).join("php-8.5.11");
        fs::create_dir_all(base.join("ext/x")).unwrap();
        fs::write(base.join("LICENSE"), b"licence").unwrap();
        fs::write(base.join("ext/x/x.stub.php"), b"<?php").unwrap();
    }

    fn scratch(name: &str) -> std::path::PathBuf {
        let dir =
            std::env::temp_dir().join(format!("xtask-manifest-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn an_intact_tree_verifies() {
        let root = scratch("ok");
        tree(&root);
        assert_eq!(verify(&root, &[release()]).unwrap(), Vec::<String>::new());
        let _ = fs::remove_dir_all(root);
    }

    #[test]
    fn an_edited_file_an_added_file_and_a_missing_file_each_fail() {
        let root = scratch("bad");
        tree(&root);
        let base = root.join(VENDOR_DIR).join("php-8.5.11");
        fs::write(base.join("ext/x/x.stub.php"), b"<?php // edited").unwrap();
        let errors = verify(&root, &[release()]).unwrap();
        assert_eq!(errors.len(), 1);
        assert!(errors[0].contains("ext/x/x.stub.php") && errors[0].contains("differs"));

        fs::write(base.join("ext/x/extra.stub.php"), b"<?php").unwrap();
        fs::remove_file(base.join("LICENSE")).unwrap();
        fs::create_dir_all(root.join(VENDOR_DIR).join("php-9.9.9")).unwrap();
        let errors = verify(&root, &[release()]).unwrap().join("\n");
        assert!(
            errors.contains("extra.stub.php: present but not listed"),
            "{errors}"
        );
        assert!(errors.contains("LICENSE: listed in"), "{errors}");
        assert!(errors.contains("php-9.9.9: not a release"), "{errors}");
        let _ = fs::remove_dir_all(root);
    }
}
