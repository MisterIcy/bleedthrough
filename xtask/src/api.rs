//! Public-API snapshots for domain and application crates.

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

use crate::apiscan::{self, Entry};
use crate::declaration::{Declaration, Layer};
use crate::meta::Package;

pub const HELP: &str = "\
check-api [--update]

Compares the public API of every domain and application crate with api/<crate>.txt.
With --update, rewrites the snapshots instead; the diff is then reviewed like any other change.

The API is derived from source with `syn` on the pinned stable toolchain (no nightly,
no rustdoc JSON). Known limits: items generated by macros are not seen, glob re-exports
are recorded as written and not expanded, and trait impls are recorded wherever they
appear in a public module. The architecture review checklist covers these gaps.";

pub fn scan_package(package: &Package) -> Result<Vec<Entry>, String> {
    let root = package.dir().join("src/lib.rs");
    apiscan::scan_crate(&root, &|p: &Path| {
        fs::read_to_string(p).map_err(|e| format!("{}: {e}", p.display()))
    })
}

pub fn render(name: &str, entries: &[Entry]) -> String {
    let mut text = format!(
        "# Public API of {name}. Generated by `cargo xtask check-api --update`; do not edit by hand.\n"
    );
    for entry in entries {
        text.push_str(&entry.line());
        text.push('\n');
    }
    text
}

/// Describes the difference between a snapshot and the actual API, or `None` if equal.
pub fn diff(name: &str, snapshot: &str, actual: &str) -> Option<String> {
    if snapshot == actual {
        return None;
    }
    let old: BTreeSet<&str> = snapshot.lines().collect();
    let new: BTreeSet<&str> = actual.lines().collect();
    let mut out = format!("public API of `{name}` differs from api/{name}.txt:\n");
    for line in old.difference(&new) {
        out.push_str(&format!("  - {line}\n"));
    }
    for line in new.difference(&old) {
        out.push_str(&format!("  + {line}\n"));
    }
    out.push_str("If intentional, run `cargo xtask check-api --update` and commit the snapshot.");
    Some(out)
}

pub fn run(
    declaration: &Declaration,
    packages: &[Package],
    root: &Path,
    update: bool,
) -> Vec<String> {
    let dir = root.join("api");
    let mut errors = Vec::new();
    for package in packages.iter().filter(|p| is_inner(declaration, &p.name)) {
        match scan_package(package) {
            Ok(entries) => errors.extend(compare(&dir, &package.name, &entries, update)),
            Err(e) => errors.push(format!("{}: {e}", package.name)),
        }
    }
    errors
}

fn is_inner(declaration: &Declaration, name: &str) -> bool {
    matches!(
        declaration.layer_of(name),
        Some(Layer::Domain | Layer::Application)
    )
}

fn compare(dir: &Path, name: &str, entries: &[Entry], update: bool) -> Option<String> {
    let actual = render(name, entries);
    let file: PathBuf = dir.join(format!("{name}.txt"));
    if update {
        let written = fs::create_dir_all(dir).and_then(|()| fs::write(&file, &actual));
        return written.err().map(|e| format!("{}: {e}", file.display()));
    }
    match fs::read_to_string(&file) {
        Ok(snapshot) => diff(name, &snapshot, &actual),
        Err(_) => Some(format!(
            "missing snapshot {}; run `cargo xtask check-api --update`",
            file.display()
        )),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(path: &str) -> Entry {
        Entry {
            path: path.into(),
            kind: "fn".into(),
            signature: String::new(),
            is_type: false,
            docs: vec![],
        }
    }

    #[test]
    fn identical_surfaces_match() {
        let text = render("c", &[entry("crate::a")]);
        assert!(diff("c", &text, &text).is_none());
    }

    #[test]
    fn newly_public_item_is_reported_and_updating_resolves_it() {
        let snapshot = render("c", &[]);
        let actual = render("c", &[entry("crate::leaked")]);
        let report = diff("c", &snapshot, &actual).unwrap();
        assert!(report.contains("+ crate::leaked fn"));
        assert!(diff("c", &actual, &actual).is_none());
    }
}
